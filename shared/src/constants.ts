/**
 * BioSphere domain constants.
 *
 * The living atlas is the single source of truth for the client, the API, and
 * the tests. Every tracked species carries the same six comparable metrics so
 * that population health, extinction risk, and range movement stay meaningful
 * across taxa.
 */

export interface CatalogMetric {
  key: string;
  label: string;
  unit: string;
  format: 'number' | 'percent' | 'compact';
  higherIsBetter: boolean;
  /** Upper bound used by compact metric bars and client previews. */
  max?: number;
}

export interface CatalogEntity {
  id: string;
  name: string;
  category: Category;
  region: Region;
  status: EntityStatus;
  summary: string;
  metrics: Record<string, number>;
  tags: string[];
}

export interface SimulationAction {
  id: string;
  label: string;
  description: string;
  severity: 'low' | 'medium' | 'high' | 'critical';
}

